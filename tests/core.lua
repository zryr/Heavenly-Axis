test("Clamped group scaling preserves the opposite handle corner", function()
    local source = { { x = 0, y = 0, w = 20, h = 20 }, { x = 40, y = 40, w = 40, h = 40 } }
    local scaled = Geometry.scale(source, { x = 60, y = 60, w = 20, h = 20 })
