local Util = require("Util")
local Geometry = require("Geometry")
local Identity = require("Identity")
local History = require("History")
local Config = require("Config")
local count = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    assert(ok, name .. ": " .. tostring(err))
    count = count + 1
end
local function equal(actual, expected) assert(Util.equal(actual, expected), "values differ") end
local function near(actual, expected) assert(math.abs(actual - expected) < 0.000001, tostring(actual) .. " ~= " .. tostring(expected)) end
local function descriptor(name)
    return { class = "Frame", path = { { name = "HUD", class = "ScreenGui", ordinal = 1 }, { name = name or "Health", class = "Frame", ordinal = 1 } } }
end
local function entry(name, x)
    local desc = descriptor(name)
    return { descriptor = desc, position = { xs = 0.5, xo = x or 0, ys = 0.5, yo = 0 },
        size = { xs = 0, xo = 100, ys = 0, yo = 40 }, viewport = { w = 1280, h = 720 } }
end
local function profile(id, scope, scopeId, x, device, orientation)
    local value = entry("Health", x)
    return { id = id, name = id, scope = scope, scopeId = scopeId, device = device, orientation = orientation,
        layout = { [Identity.key(value.descriptor)] = value }, groups = {}, preferences = {} }
end
local context = { experience = "1", place = "2", device = "touch", orientation = "landscape" }
local function activeData(profiles)
    local data = Config.empty()
    for _, value in ipairs(profiles) do
        data.profiles[#data.profiles + 1] = value
        data.active[Config.scopeKey(value)] = value.id
    end
    return data
end
local function node(name, class, parent)
    local value = { Name = name, ClassName = class, Parent = parent, children = {} }
    function value:GetChildren() return self.children end
    if parent then parent.children[#parent.children + 1] = value end
    return value
end

