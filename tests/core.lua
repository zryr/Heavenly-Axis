test("History creates one step per completed action", function()
    local history = History.new(3)
    history:checkpoint({ x = 0 })
    assert(not history:push({ x = 0 }, { x = 0 }))
    assert(history:push({ x = 0 }, { x = 20 }, "Drag"))
    equal(history:undo(), { x = 0 })
    equal(history:redo(), { x = 20 })
end)
test("Saving keeps undo and undoing saved state becomes dirty", function()
    local history = History.new()
    history:push({ x = 0 }, { x = 20 }, "Move")
    history:checkpoint({ x = 20 })
    assert(not history:dirty({ x = 20 }))
    local previous = history:undo()
    assert(previous.x == 0 and history:dirty(previous))
    assert(not history:dirty(history:redo()))
end)
test("Cancel restores saved checkpoint and starts a clean history", function()
    local history = History.new()
    history:checkpoint({ x = 20 })
    history:push({ x = 20 }, { x = 50 })
    equal(history:cancel(), { x = 20 })
    assert(history:undo() == nil and history:redo() == nil)
end)
test("New edits after undo invalidate redo", function()
    local history = History.new()
    history:push({ x = 0 }, { x = 10 }); history:undo()
    history:push({ x = 0 }, { x = 20 })
    assert(history:redo() == nil)
end)
test("History is bounded", function()
    local history = History.new(2)
    for x = 1, 4 do history:push({ x = x - 1 }, { x = x }) end
    assert(history:undo().x == 3 and history:undo().x == 2 and history:undo() == nil)
end)
test("History return values do not mutate saved history", function()
    local history = History.new()
    history:push({ x = 0 }, { x = 10 })
    local value = history:undo(); value.x = 99
    assert(history:redo().x == 10 and history:undo().x == 0)
end)
