test("Sibling ambiguity survives descriptor generation", function()
    local root = node("PlayerGui", "PlayerGui")
    local hud = node("HUD", "ScreenGui", root)
    local first = node("Health", "Frame", hud); node("Health", "Frame", hud)
    local desc = Identity.descriptor(first, root)
