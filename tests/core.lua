test("More-specific settings override only their keys", function()
    local e, p, d, o = profile("experience", "experience", "1", 10), profile("place", "place", "2", 20),
        profile("device", "device", "2", 30, "touch"), profile("orientation", "orientation", "2", 40, "touch", "landscape")
    e.preferences.grid, p.preferences.step, d.preferences.snapping = false, 4, true
