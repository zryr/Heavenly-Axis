    equal(Geometry.scale({tiny}, {x = tiny.x, y = tiny.y, w = 7, h = 8}, false)[1], tiny)
    local growth = Geometry.resize(tiny, "se", 2, 0, false, false)
    near(growth.w, 10)
    near(growth.h, 10)
