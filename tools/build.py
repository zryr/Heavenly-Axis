#!/usr/bin/env python3
"""Bundle Heavenly Axis's modules without runtime source loading."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = (ROOT / "dist/HeavenlyAxis.lua", ROOT / "Source")


def bundle() -> str:
    files = sorted((ROOT / "src").glob("*.lua"))
    modules = {path.stem: path.read_text(encoding="utf-8").replace("\r\n", "\n") for path in files}
    if "Bootstrap" not in modules:
        raise ValueError("src/Bootstrap.lua is required")
    for name, source in modules.items():
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
            raise ValueError(f"Invalid module filename: {name}")
        for dependency in re.findall(r'\brequire\s*\(\s*[\"\']([^\"\']+)[\"\']\s*\)', source):
            if dependency not in modules:
                raise ValueError(f"{name} requires missing module {dependency}")
    digest = hashlib.sha256("".join(name + "\0" + source for name, source in modules.items()).encode()).hexdigest()
    sections = [
        "-- Heavenly Axis V3 | Roblox HUD & Interface Editor\n"
        "-- Original by Syshi. V2 inspired by Danechka.\n"
        "-- Generated by tools/build.py; edit src/*.lua instead.\n"
        "-- https://github.com/zryr/Heavenly-Axis\n"
        f"-- Source SHA-256: {digest}\n\n"
        "local __factories, __cache, __loading = {}, {}, {}\n"
        "local function __require(name)\n"
        "    if __cache[name] ~= nil then return __cache[name] end\n"
        "    assert(not __loading[name], 'Cyclic Heavenly Axis module: ' .. tostring(name))\n"
        "    local factory = assert(__factories[name], 'Missing Heavenly Axis module: ' .. tostring(name))\n"
        "    __loading[name] = true\n"
        "    local ok, result = pcall(factory, __require)\n"
        "    __loading[name] = nil\n"
        "    if not ok then error(result, 0) end\n"
        "    if result == nil then result = true end\n"
        "    __cache[name] = result\n"
        "    return result\n"
        "end\n",
    ]
    for name, source in modules.items():
        sections.append(f'\n-- Module: {name}\n__factories["{name}"] = function(require)\n{source.rstrip()}\nend\n')
    sections.append('\nreturn __require("Bootstrap")\n')
    return "".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if either tracked release differs from source")
    args = parser.parse_args()
    try:
        content = bundle()
    except (ValueError, OSError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    stale = []
    for target in OUTPUTS:
        if args.check:
            if not target.exists() or target.read_bytes() != content.encode("utf-8"):
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content.encode("utf-8"))
            print(f"Built {target.relative_to(ROOT)} ({len(content.encode('utf-8')):,} bytes)")
    if stale:
        print("Stale release: " + ", ".join(stale) + "; run python3 tools/build.py", file=sys.stderr)
        return 1
    if args.check:
        print("Passed: both release artifacts match a deterministic rebuild")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
